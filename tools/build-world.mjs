#!/usr/bin/env node
// tools/build-world.mjs — ARCIRCLE World's code, minified, for play.html.
//
// The game is ~45 ES modules (world-*.js, 1.35 MB as written). Phones paid for every byte and every file. This
// bundles them with esbuild into /w/:
//   w/world-studio-web.js  a second entry: the Studio's web page (studio-web.html, /game/@<creator>/<game>), sharing the chunks
//   w/world-play.js   the entry (the beta check, then the game); loaded as /w/world-play.js?v=N so the asset
//                     version (VER, read from its own URL) keeps working
//   w/c-<hash>.js     the rest: world-all.js and everything it pulls in, plus the parts loaded on demand (the 3D
//                     preview, N8AO, the reflector, SMAA), each named by its content so caches stay right
// three.js itself stays the shared file /vendor/three/three-0.186.1.module.min.js (already minified, cached
// across pages). No source maps (each build would add megabytes to the repository); the sources are next door.
//
// play.html's block between <!-- world-build --> and <!-- /world-build --> is rewritten with the module preloads.
// Edit the source files, never /w/. bump-cache.sh runs this.
//
//   node tools/build-world.mjs           build (needs esbuild; without it play.html loads the source modules)
//   node tools/build-world.mjs --check   fail if /w/ is older than the sources
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "w");
const THREE_URL = "/vendor/three/three-0.186.1.module.min.js";
const PLAY = path.join(ROOT, "play.html");

// the sources: every world-*.js the entry reaches, and the three.js add-ons
function sources() {
  const list = fs.readdirSync(ROOT).filter((f) => /^world-[a-z0-9-]+\.js$/.test(f)).sort();
  const addons = fs.readdirSync(path.join(ROOT, "vendor/three/addons")).filter((f) => f.endsWith(".js")).sort().map((f) => "vendor/three/addons/" + f);
  return [...list, ...addons];
}
function srcHash() {
  const h = crypto.createHash("sha256");
  for (const f of sources()) { h.update(f); h.update(fs.readFileSync(path.join(ROOT, f))); }
  h.update(fs.readFileSync(fileURLToPath(import.meta.url)));
  return h.digest("hex").slice(0, 16);
}
const STAMP = path.join(OUT, ".src-hash");
// 2026-10-29: world-words.js (all three languages, ~840 KB) is split into gen/words-<lang>.js so a player loads only
// their language (world-words-load.js); written here from the source, only when its content changes
function genWords() {
  const vm = require_vm(); const src = fs.readFileSync(path.join(ROOT, "world-words.js"), "utf8");
  const W = vm.runInNewContext(src.replace(/^export const WORDS =/m, "const WORDS =") + "\nWORDS", {});
  fs.mkdirSync(path.join(ROOT, "gen"), { recursive: true }); const out = {};
  for (const l of ["ko", "zh", "tr"]) { const f = path.join(ROOT, "gen", `words-${l}.js`), body = "// generated by tools/build-world.mjs from world-words.js — edit that file, not this one\nexport default " + JSON.stringify(W[l] || {}) + ";\n"; let cur = ""; try { cur = fs.readFileSync(f, "utf8"); } catch { cur = ""; } if (cur !== body) fs.writeFileSync(f, body); out[l] = body.length; }
  return out;
}
let require_vm = () => null; try { const { createRequire } = await import("node:module"); const req = createRequire(import.meta.url); require_vm = () => req("node:vm"); } catch { /* below */ }
genWords();
const stamp = () => { try { return fs.readFileSync(STAMP, "utf8").trim(); } catch { return ""; } };

// play.html: the block of module preloads and the script tag
function writePlay(useBuild, preloads, wordsMap = {}) {
  let html = fs.readFileSync(PLAY, "utf8");
  const ver = (/\?v=(\d+)/.exec(html) || [])[1] || "1";
  const a = html.indexOf("<!-- world-build -->"), b = html.indexOf("<!-- /world-build -->");
  if (a < 0 || b < a) throw new Error("play.html has no <!-- world-build --> block");
  const lines = useBuild
    ? [`<link rel="modulepreload" href="/w/world-play.js?v=${ver}">`, ...preloads.map((f) => `<link rel="modulepreload" href="/w/${f}">`),
      // the player's language's words chunk, fetched alongside the rest (the game asks for it as soon as it starts)
      ...(Object.keys(wordsMap).length ? [`<script>(function(){var m=${JSON.stringify(wordsMap)};try{var q=/[?&]lang=(en|ko|zh|tr)(?:&|$)/.exec(location.search),n=(navigator.language||"").toLowerCase(),l=q?q[1]:localStorage.getItem("arcircle.lang")||(n.indexOf("ko")===0?"ko":n.indexOf("zh")===0?"zh":n.indexOf("tr")===0?"tr":"en"),f=m[l];if(f){var k=document.createElement("link");k.rel="modulepreload";k.href="/w/"+f;document.head.appendChild(k);}}catch(e){}})();</script>`] : [])]
    : ["<!-- the source modules (no build): world-play.js imports world-all.js, which imports the rest -->", `<link rel="modulepreload" href="/world-play.js?v=${ver}">`, `<link rel="modulepreload" href="/world-all.js">`];
  html = html.slice(0, a) + "<!-- world-build -->\n" + lines.join("\n") + "\n" + html.slice(b);
  html = html.replace(/<script type="module" src="\/(?:w\/)?world-play\.js\?v=\d+"><\/script>/, `<script type="module" src="/${useBuild ? "w/" : ""}world-play.js?v=${ver}"></script>`);
  fs.writeFileSync(PLAY, html);
}

// 2026-10-29: every chunk the live deploy has (origin/main's w/) stays, listed in a generation or not — local builds
// between two deploys (and a merge that kept one side's .gens.json) used to drop shipped chunks that pages opened
// before the deploy still ask for. Deploys, not local builds, decide what goes; a chunk with merge marks is never put back.
async function keepShipped() {
  let n = 0;
  try {
    const { execFileSync } = await import("node:child_process"), git = (a, enc) => execFileSync("git", a, { cwd: ROOT, maxBuffer: 64 << 20, stdio: ["ignore", "pipe", "ignore"], ...(enc ? { encoding: "utf8" } : {}) });
    let ref = "origin/main"; try { git(["rev-parse", "--verify", ref], true); } catch { ref = "HEAD"; }
    for (const f of git(["ls-tree", "--name-only", ref, "w/"], true).split("\n").map((l) => l.trim().replace(/^w\//, "")).filter((l) => /^c-[A-Z0-9]+\.js$/.test(l))) {
      const p = path.join(OUT, f); if (fs.existsSync(p)) continue;
      let buf = null; try { buf = git(["show", ref + ":w/" + f]); } catch { buf = null; }
      if (buf && !/^(<{7}|>{7}) /m.test(buf.toString("utf8", 0, Math.min(buf.length, 2e6)))) { fs.writeFileSync(p, buf); n++; }
    }
  } catch { /* not a git checkout: the generations alone */ }
  return n;
}
const check = process.argv.includes("--check");
const want = srcHash();
if (check) {
  if (stamp() !== want) { console.error("w/ is out of date: run node tools/build-world.mjs (or sh bump-cache.sh)"); process.exit(1); }
  console.log("w/ is up to date"); process.exit(0);
}

let esbuild = null;
try { esbuild = await import("esbuild"); } catch { try { esbuild = (await import("node:module")).createRequire(import.meta.url)("esbuild"); } catch { esbuild = null; } } // NODE_PATH works through require
if (!esbuild) {
  if (stamp() === want && fs.existsSync(path.join(OUT, "world-play.js"))) { console.log("world build: esbuild not found, /w/ already matches the sources"); process.exit(0); }
  // never ship a stale build: without esbuild, play.html goes back to the source modules
  writePlay(false, []);
  console.warn("WARNING: esbuild not found and /w/ is out of date — play.html now loads the source modules (npm i --no-save esbuild@0.24 to build)");
  process.exit(0);
}
if (stamp() === want && fs.existsSync(path.join(OUT, "world-play.js")) && !process.argv.includes("--force")) {
  const keep = JSON.parse(fs.readFileSync(path.join(OUT, ".preload.json"), "utf8"));
  let wm = {}; try { wm = JSON.parse(fs.readFileSync(path.join(OUT, ".words.json"), "utf8")); } catch { wm = {}; }
  writePlay(true, keep, wm);
  const back = await keepShipped();
  console.log("world build: up to date" + (back ? ` (${back} shipped chunks put back)` : ""));
  process.exit(0);
}

// a clean folder (only ever ROOT/w) — the last builds' chunks come back after the build, see KEEP_GENS
if (path.basename(OUT) !== "w" || path.dirname(OUT) !== ROOT) throw new Error("refusing to clear " + OUT);
// Chunks are named by their content and a deploy replaces the whole folder. A page opened before a deploy still asks
// for the chunk names it was built with (AC Defense, the 3D preview and the add-ons load on demand), and a name that
// is gone is a 404: the feature never opens until the page is reloaded. So older builds' chunks stay in /w/ next to the
// new ones (w/.gens.json lists the generations, newest first, each with the time it was built): always the last
// KEEP_GENS builds, and every build of the last KEEP_DAYS days (at most MAX_GENS). By time, not by count: several builds
// between two deploys (2026-10-20) once pushed the live build's chunks out, and pages opened before the deploy broke.
const KEEP_GENS = 3, KEEP_DAYS = 7, MAX_GENS = 40, GENS = path.join(OUT, ".gens.json");
let gens = []; try { gens = JSON.parse(fs.readFileSync(GENS, "utf8")).filter((g) => g && Array.isArray(g.files)); } catch { /* first build that keeps generations */ }
const old = new Map(); // chunk name → bytes, everything that was in the folder before this build
try { for (const f of fs.readdirSync(OUT)) if (/^c-[A-Z0-9]+\.js$/.test(f)) old.set(f, fs.readFileSync(path.join(OUT, f))); } catch { /* no folder yet */ }
if (!gens.length && old.size) gens = [{ files: [...old.keys()].sort() }]; // a folder from before generations were kept counts as one
const prev = new Map(); // every file in /w/ before this build (entry, stamps, chunks): what a failed build puts back
try { for (const f of fs.readdirSync(OUT)) prev.set(f, fs.readFileSync(path.join(OUT, f))); } catch { /* no folder yet */ }
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT);
const threeExternal = {
  name: "three-external",
  setup(b) { b.onResolve({ filter: /three-0\.186\.1\.module\.min\.js$/ }, () => ({ path: THREE_URL, external: true })); },
};
// a failed build must not leave /w/ empty (the live page would have nothing to load): the old chunks are already in
// memory (old) and come back below; on an error, put them back and stop
let res;
try { res = await esbuild.build({
  absWorkingDir: ROOT, entryPoints: ["world-play.js", "world-studio-web.js"], outdir: OUT, bundle: true, splitting: true, format: "esm",
  minify: true, target: ["es2022"], sourcemap: false, entryNames: "[name]", chunkNames: "c-[hash]", metafile: true, charset: "utf8", /* (2026-10-29: Korean / Chinese / Turkish text as UTF-8, not \uXXXX — the words chunks at half the bytes) */
  legalComments: "eof", plugins: [threeExternal], logLevel: "warning",
}); } catch (err) {
  for (const [f, bytes] of prev) fs.writeFileSync(path.join(OUT, f), bytes);
  console.error("world build FAILED — /w/ chunks put back; fix the error above and build again"); process.exit(1);
}
// what to preload: the chunks the entry needs at start (static imports) and the game's chunk (world-all.js)
const outs = res.metafile.outputs, rel = (p) => path.relative(OUT, path.join(ROOT, p));
const entry = Object.keys(outs).find((k) => outs[k].entryPoint === "world-play.js");
const pre = new Set();
for (const im of outs[entry].imports) if (im.kind === "import-statement" && !im.external) pre.add(rel(im.path));
const allChunk = Object.keys(outs).find((k) => outs[k].inputs && outs[k].inputs["world-all.js"]);
if (allChunk) { pre.add(rel(allChunk)); for (const im of outs[allChunk].imports) if (im.kind === "import-statement" && !im.external) pre.add(rel(im.path)); }
const preloads = [...pre].filter((f) => f.endsWith(".js"));
fs.writeFileSync(path.join(OUT, ".preload.json"), JSON.stringify(preloads));
// the words chunks by language (play.html preloads the player's one)
fs.writeFileSync(path.join(OUT, ".meta.json"), JSON.stringify(res.metafile)); /* (what each chunk holds) */
const wordsMap = {}; for (const l of ["ko", "zh", "tr"]) { const k = Object.keys(outs).find((o) => outs[o].inputs && outs[o].inputs[`gen/words-${l}.js`]); /* (a dynamic import's target is listed as its own entry point) */ if (k) wordsMap[l] = rel(k); }
fs.writeFileSync(path.join(OUT, ".words.json"), JSON.stringify(wordsMap));
if (!Object.keys(wordsMap).length) console.warn("words chunks not found in the metafile:", Object.keys(outs).filter((o) => /words/.test(JSON.stringify(Object.keys(outs[o].inputs || {})))).map((o) => o + " " + Object.keys(outs[o].inputs).filter((i) => /words/.test(i)).join(",")).join(" | ").slice(0, 400));
fs.writeFileSync(STAMP, want + "\n");
// the generations: this build first (unless it's the same set as the last one), then the kept older ones, restored
const chunks = Object.keys(outs).map((k) => path.basename(k)).filter((f) => /^c-[A-Z0-9]+\.js$/.test(f)).sort();
const nowMs = Date.now();
if (!(gens.length && JSON.stringify(gens[0].files) === JSON.stringify(chunks))) gens = [{ files: chunks, at: nowMs }, ...gens];
gens = gens.map((g) => (g.at ? g : { ...g, at: nowMs })) // (a generation from before times were kept: from now)
  .filter((g, i) => i < KEEP_GENS || nowMs - g.at < KEEP_DAYS * 864e5).slice(0, MAX_GENS);
let kept = 0;
for (const g of gens.slice(1)) for (const f of g.files) { const p = path.join(OUT, f); if (!fs.existsSync(p) && old.has(f)) { fs.writeFileSync(p, old.get(f)); kept++; } }
kept += await keepShipped();
fs.writeFileSync(GENS, JSON.stringify(gens));
writePlay(true, preloads, wordsMap);
// /studio (studio-app.html): world-studio-web.js's own imports and the modules its app mode loads at once (the kit, the
// Studio, its sounds and pads) preloaded side by side — they came one after another, a chain of ~2.5 s on a phone
{ const want = ["world-kit.js", "world-studio.js", "world-sfx.js", "world-studio-pad.js"], set = new Set();
  const addDeps = (k) => { if (!k || set.has(rel(k))) return; set.add(rel(k)); for (const im of outs[k].imports) if (im.kind === "import-statement" && !im.external) addDeps(im.path); };
  const sEntry = Object.keys(outs).find((k) => outs[k].entryPoint === "world-studio-web.js");
  for (const im of outs[sEntry].imports) if (im.kind === "import-statement" && !im.external) addDeps(im.path);
  for (const w of want) addDeps(Object.keys(outs).find((k) => outs[k].entryPoint === w || (outs[k].inputs && outs[k].inputs[w])));
  const APP = path.join(ROOT, "studio-app.html");
  let html = fs.readFileSync(APP, "utf8"); const a = html.indexOf("<!-- studio-build -->"), b = html.indexOf("<!-- /studio-build -->");
  if (a >= 0 && b > a) { const lines = [`<link rel="modulepreload" href="${THREE_URL}">`, ...[...set].filter((f) => f.endsWith(".js")).map((f) => `<link rel="modulepreload" href="/w/${f}">`)]; html = html.slice(0, a) + "<!-- studio-build -->\n" + lines.join("\n") + "\n" + html.slice(b); fs.writeFileSync(APP, html); } }
let total = 0; for (const k of Object.keys(outs)) if (k.endsWith(".js")) total += outs[k].bytes;
console.log(`world build: ${Object.keys(outs).filter((k) => k.endsWith(".js")).length} files, ${(total / 1024).toFixed(0)} KB (preload ${preloads.length + 1}, ${kept} older chunks kept for pages opened before this deploy)`);
